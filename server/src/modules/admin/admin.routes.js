import { Router } from 'express';
import { ah } from '../../core/http.js';
import { authenticate, requireSuperAdmin } from '../../core/auth.js';
import * as C from './admin.controller.js';

const router = Router();
router.use(authenticate, requireSuperAdmin);
router.get('/dashboard', ah(C.dashboard));
router.get('/orgs', ah(C.orgs));
router.get('/orgs/:id', ah(C.org));
router.put('/orgs/:id', ah(C.updateOrg));
router.post('/orgs/:id/approve', ah(C.approve));
router.post('/orgs/:id/reject', ah(C.setStatus('rejected', 'rejected')));
router.post('/orgs/:id/suspend', ah(C.setStatus('suspended', 'suspended')));
router.post('/orgs/:id/reactivate', ah(C.reactivate));
router.put('/orgs/:id/features', ah(C.orgFeatures));
router.post('/orgs/:id/notes', ah(C.addNote));
router.post('/features/bulk', ah(C.bulkFeatures));
router.get('/features', ah(C.features));
router.put('/features/:code', ah(C.updateFeature));
router.get('/plans', ah(C.plans));
router.post('/plans', ah(C.savePlan));
router.put('/plans/:id', ah(C.savePlan));
router.get('/billing', ah(C.billing));
router.get('/invoices', ah(C.invoices));
router.post('/invoices/generate', ah(C.generateInvoices));
router.put('/invoices/:id', ah(C.setInvoice));
router.get('/admins', ah(C.admins));
router.post('/admins', ah(C.saveAdmin));
router.put('/admins/:id', ah(C.saveAdmin));
router.get('/audit', ah(C.auditLog));
export default router;
